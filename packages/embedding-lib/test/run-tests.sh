#!/usr/bin/env bash
# Tests for embedding-lib.
#
# Redirects HOME and CLAUDE_DIR into a temp directory, so the real config is
# never touched. The installer tests come free, from installer-tests.sh, which
# claude-package-kit keeps up to date. This file is the package's own.
#
# Two groups of behaviour tests:
#
#   setup and refusals — stubbed curl, uname and df, no network, no real
#   environment. Every refusal setup and the commands make.
#
#   the real environment — run against a home that `embedding-lib setup`
#   has already built, named by EMBEDDING_LIB_TEST_HOME, because building one
#   is a 1.9 GB download. They embed for real, with the network shut off.
#   Without EMBEDDING_LIB_TEST_HOME they fail, unless EMBEDDING_LIB_SKIP_REAL=1
#   says leaving them out was meant.
#
#   EMBEDDING_LIB_TEST_HOME=<home> ./test/run-tests.sh
#
# Logs to /tmp/embedding-lib-tests.log as well as the terminal.
set -uo pipefail

LOGFILE="${EMBEDDING_LIB_TEST_LOG:-/tmp/embedding-lib-tests.log}"
exec > >(tee "$LOGFILE") 2>&1

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
REAL_HOME_DIR="${EMBEDDING_LIB_TEST_HOME:-}"
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
export HOME="$TMP/home"; mkdir -p "$HOME"
export CLAUDE_DIR="$TMP/claude"; mkdir -p "$CLAUDE_DIR"
export KIT_SKIP_MACHINE_HOOKS=1   # pre_install and post_install change the real machine, not $HOME
unset EMBEDDING_LIB_HOME EMBEDDING_LIB_LOG

pass=0; fail=0
ok(){ printf '  ok    %s\n' "$1"; pass=$((pass+1)); }
no(){ printf '  FAIL  %s\n    %s\n' "$1" "$2"; fail=$((fail+1)); }
has(){ case "$2" in *"$3"*) ok "$1" ;; *) no "$1" "expected '$3' in: $2" ;; esac; }

. "$REPO/test/installer-tests.sh"

B="$REPO/bin/embedding-lib"

echo
echo "pins"
. "$REPO/pylib/runtime.env"
[ "$PY_VERSION" = 3.14.10 ] && ok "runtime.env bundles Python 3.14.10" || no "runtime.env Python" "$PY_VERSION"
for a in x86_64 aarch64; do
  v="SHA256_$a"
  [[ "${!v:-}" =~ ^[0-9a-f]{64}$ ]] && ok "runtime.env has a SHA256 for $a" || no "SHA256 for $a" "${!v:-missing}"
done
grep -q '^# Generated by tools/pin-python.sh' "$REPO/pylib/runtime.env" \
  && ok "runtime.env says which tool generated it" || no "runtime.env header" "no generated-by line"
while read -r pin; do
  case "$pin" in ''|\#*) continue ;; esac
  grep -qx "${pin} \\\\" "$REPO/pylib/requirements.txt" \
    && ok "the lock pins $pin, as requirements.in asks" || no "lock pins $pin" "requirements.txt is out of date: run tools/lock.sh"
done < "$REPO/pylib/requirements.in"
bad=$(awk '/^[a-zA-Z]/ {p=$1} /^[a-zA-Z].*==/ && !/\\$/ {print p}' "$REPO/pylib/requirements.txt")
nohash=$(awk '/^[a-zA-Z]/ {if (p && !h) print p; p=$1; h=0} /--hash=sha256:/ {h=1} END {if (p && !h) print p}' "$REPO/pylib/requirements.txt")
[ -z "$nohash" ] && ok "every locked package has a hash" || no "hashes in the lock" "without: $nohash $bad"
rev=$(sed -n 's/^REVISION = "\([0-9a-f]*\)".*/\1/p' "$REPO/pylib/embedding_lib/__init__.py")
[ "$rev" = a5beb1e3e68b9ab74eb54cfd186867f64f240e1a ] && ok "the model is pinned at commit a5beb1e3" || no "model revision" "$rev"

echo
echo "setup and refusals (stubbed, no network)"
STUB="$TMP/stub"; mkdir -p "$STUB"
CALLS="$TMP/curl-calls"; : > "$CALLS"
cat > "$STUB/curl" <<EOF
#!/usr/bin/env bash
echo "\$*" >> "$CALLS"
# -o <file> <url>: write a tarball that isn't the pinned one
while [ \$# -gt 0 ]; do [ "\$1" = -o ] && { printf 'not the real tarball' > "\$2"; }; shift; done
exit 0
EOF
cat > "$STUB/uname" <<'EOF'
#!/usr/bin/env bash
[ "$1" = -m ] && { echo "${FAKE_ARCH:-x86_64}"; exit 0; }
exec /bin/uname "$@"
EOF
cat > "$STUB/df" <<'EOF'
#!/usr/bin/env bash
printf 'Filesystem 1M-blocks Used Available Capacity Mounted\nfake 100000 0 %s 0%% /\n' "${FAKE_FREE_MB:-50000}"
EOF
chmod +x "$STUB"/*
run() { PATH="$STUB:$PATH" EMBEDDING_LIB_HOME="$TMP/h" EMBEDDING_LIB_LOG="$TMP/setup.log" "$B" "$@" 2>&1; }

out=$(run setup </dev/null); rc=$?
[ "$rc" -ne 0 ] && ok "setup with no terminal and no --yes refuses" || no "setup without --yes" "exit $rc"
has "and says to use --yes" "$out" "setup --yes"
[ ! -s "$CALLS" ] && ok "and downloads nothing" || no "no download without --yes" "$(cat "$CALLS")"
[ -s "$TMP/setup.log" ] && ok "setup logs to EMBEDDING_LIB_LOG" || no "setup log" "nothing in $TMP/setup.log"

out=$(run setup --yes); rc=$?
[ "$rc" -ne 0 ] && ok "a tarball whose SHA256 doesn't match is refused" || no "SHA256 refusal" "exit $rc"
has "naming the mismatch" "$out" "SHA256"
[ ! -e "$TMP/h/python" ] && ok "and no Python is installed" || no "nothing installed on mismatch" "$(ls "$TMP/h")"
ls -d "$TMP/h"/.python.* >/dev/null 2>&1 && no "temp files cleaned up" "$(ls -a "$TMP/h")" || ok "and its temp directory is removed"
has "the download names the pinned release" "$(cat "$CALLS")" "/20261026/cpython-3.14.10%2B20261026-x86_64-unknown-linux-gnu-install_only_stripped.tar.gz"

: > "$CALLS"
out=$(FAKE_ARCH=aarch64 run setup --yes)
has "aarch64 machines get the aarch64 tarball" "$(cat "$CALLS")" "aarch64-unknown-linux-gnu"

: > "$CALLS"
out=$(FAKE_ARCH=riscv64 run setup --yes); rc=$?
[ "$rc" -ne 0 ] && ok "an unpinned machine type is refused" || no "arch refusal" "exit $rc"
has "naming it" "$out" "riscv64"
[ ! -s "$CALLS" ] && ok "before anything is downloaded" || no "no download for riscv64" "$(cat "$CALLS")"

out=$(FAKE_FREE_MB=500 run setup --yes); rc=$?
[ "$rc" -ne 0 ] && ok "too little disk is refused" || no "disk refusal" "exit $rc"
has "with what it needs and what there is" "$out" "has 500 MB"

out=$(run embed </dev/null); rc=$?
[ "$rc" -eq 4 ] && ok "embed before setup exits 4" || no "embed before setup" "exit $rc"
has "and says to run setup" "$out" "not set up; run: embedding-lib setup"

mkdir -p "$TMP/h/venv/bin"
printf '#!/bin/sh\nexit 1\n' > "$TMP/h/venv/bin/python"; chmod +x "$TMP/h/venv/bin/python"
out=$(run identity); rc=$?
[ "$rc" -eq 4 ] && has "a venv whose Python no longer starts is reported" "$out" "no longer starts" \
  || no "broken venv" "exit $rc: $out"

printf '#!/bin/sh\nexit 0\n' > "$TMP/h/venv/bin/python"
echo "an older release" > "$TMP/h/.venv-stamp"
out=$(run identity); rc=$?
[ "$rc" -eq 4 ] && has "a venv built for other pins is refused" "$out" "different release" \
  || no "stale venv" "exit $rc: $out"

out=$(run paths)
has "paths names the interpreter dependents use" "$out" "python $TMP/h/venv/bin/python"

out=$("$B" bogus 2>&1); rc=$?
[ "$rc" -eq 2 ] && ok "an unknown command exits 2" || no "unknown command" "exit $rc"

echo
echo "the real environment"
if [ -z "$REAL_HOME_DIR" ]; then
  if [ "${EMBEDDING_LIB_SKIP_REAL:-0}" = 1 ]; then
    echo "  skip  EMBEDDING_LIB_SKIP_REAL=1: not run"
  else
    no "real-environment tests" "set EMBEDDING_LIB_TEST_HOME to a home built by 'embedding-lib setup' (or EMBEDDING_LIB_SKIP_REAL=1)"
  fi
else
  # No network: an unreachable proxy for everything, and Hugging Face pointed
  # at a closed port. A download attempt fails instead of quietly succeeding.
  real() {
    EMBEDDING_LIB_HOME="$REAL_HOME_DIR" EMBEDDING_LIB_LOG="$TMP/real-setup.log" \
    https_proxy=http://127.0.0.1:9 HTTPS_PROXY=http://127.0.0.1:9 \
    http_proxy=http://127.0.0.1:9 HTTP_PROXY=http://127.0.0.1:9 \
    HF_ENDPOINT=http://127.0.0.1:9 PATH="$STUB:$PATH" "$B" "$@"
  }
  : > "$CALLS"
  out=$(real setup 2>&1)
  has "setup on a complete home downloads nothing" "$out" "nothing to download"
  [ ! -s "$CALLS" ] && ok "and calls no curl" || no "setup idempotent" "$(cat "$CALLS")"

  out=$(real check 2>&1); rc=$?
  [ "$rc" -eq 0 ] && has "check embeds offline and passes" "$out" '"ok": true' || no "check" "exit $rc: $out"

  out=$(printf '{"id":1,"text":"Can you review the PR?"}\n{"id":"two","text":"Please take a look at my pull request"}\n{"id":3,"text":"The weather is nice today"}\n{"id":4,"text":"Can you review the PR?"}\n' | real embed 2>&1)
  printf '%s\n' "$out" > "$TMP/vecs.jsonl"
  res=$(python3 - "$TMP/vecs.jsonl" <<'PY'
import json, sys, math
rows = [json.loads(l) for l in open(sys.argv[1])]
v = {r["id"]: r["vector"] for r in rows}
dot = lambda a, b: sum(x*y for x, y in zip(a, b))
print(len(rows), [r["id"] for r in rows] == [1, "two", 3, 4],
      all(len(x) == 768 for x in v.values()),
      all(abs(math.sqrt(dot(x, x)) - 1) < 1e-4 for x in v.values()),
      dot(v[1], v["two"]) > dot(v[1], v[3]),
      v[1] == v[4])
PY
)
  [ "$res" = "4 True True True True True" ] && ok "embed: one line per input, ids kept, 768 wide, unit length, related closer, same text same vector" \
    || no "embed output" "$res / $(head -c 300 "$TMP/vecs.jsonl")"

  out=$(printf '' | real embed 2>&1); rc=$?
  [ "$rc" -eq 0 ] && [ -z "$out" ] && ok "embed with no input prints nothing" || no "empty embed" "exit $rc: $out"
  out=$(printf 'not json\n' | real embed 2>&1); rc=$?
  [ "$rc" -ne 0 ] && has "bad input names the line" "$out" "line 1" || no "bad input" "exit $rc"

  out=$(printf '{"id":1,"text":"hello there"}\n' | real tokens 2>&1)
  has "tokens counts as the model does, markers included" "$out" '"tokens": 4'

  id=$(real identity 2>&1)
  res=$(printf '%s' "$id" | python3 -c '
import json, sys; d = json.load(sys.stdin)
print(d["model"], d["revision"][:8], d["dimension"], d["normalised"], d["python"], d["libraries"]["torch"], len(d["lock_sha256"]))')
  [ "$res" = "BAAI/bge-base-en-v1.5 a5beb1e3 768 True 3.14.10 2.15.0+cpu 64" ] && ok "identity records model, revision, size, Python, torch and the lock's hash" \
    || no "identity" "$res"
  out=$(printf '%s' "$id" | real check-identity 2>&1); rc=$?
  [ "$rc" -eq 0 ] && ok "an index's own identity matches" || no "identity matches itself" "exit $rc: $out"
  for field in model revision dimension normalised python lock_sha256 api; do
    changed=$(printf '%s' "$id" | python3 -c "
import json, sys; d = json.load(sys.stdin); d['$field'] = 'other'; print(json.dumps(d))")
    out=$(printf '%s' "$changed" | real check-identity 2>&1); rc=$?
    [ "$rc" -eq 3 ] && has "a different $field is refused, and named" "$out" "$field: index has 'other'" \
      || no "mismatch on $field" "exit $rc: $out"
  done
  changed=$(printf '%s' "$id" | python3 -c "
import json, sys; d = json.load(sys.stdin); d['libraries']['torch'] = 'x'; print(json.dumps(d))")
  out=$(printf '%s' "$changed" | real check-identity 2>&1); rc=$?
  [ "$rc" -eq 0 ] && ok "the library list is information only; the lock's hash decides" || no "libraries informational" "exit $rc"

  # A home with the environment but no model: the library must say so, not
  # try to download it.
  NM="$TMP/nomodel"; mkdir -p "$NM"
  for f in python venv pylib .python-stamp .venv-stamp; do
    [ -e "$REAL_HOME_DIR/$f" ] && ln -s "$REAL_HOME_DIR/$f" "$NM/$f"
  done
  out=$(EMBEDDING_LIB_HOME="$NM" HF_ENDPOINT=http://127.0.0.1:9 https_proxy=http://127.0.0.1:9 \
        sh -c 'printf "{\"id\":1,\"text\":\"x\"}\n" | "$1" embed' _ "$B" 2>&1); rc=$?
  [ "$rc" -eq 4 ] && has "a missing model is reported with the command to fix it" "$out" "run: embedding-lib setup" \
    || no "missing model" "exit $rc: $out"

  out=$(EMBEDDING_LIB_HOME="$REAL_HOME_DIR" "$REAL_HOME_DIR/venv/bin/python" -c '
import embedding_lib as el
print(el.EMBEDDING_LIB_API, el.embed(["a", "b"]).shape)' 2>&1)
  has "dependents import it through the bundled interpreter" "$out" "1 (2, 768)"
  out=$(EMBEDDING_LIB_HOME="$REAL_HOME_DIR" "$REAL_HOME_DIR/venv/bin/python" -c '
import embedding_lib as el
el.embed("one string")' 2>&1)
  has "embed refuses a bare string" "$out" "takes a list of strings"
fi

printf '\n%d passed, %d failed\n' "$pass" "$fail"
[ "$fail" = 0 ]
